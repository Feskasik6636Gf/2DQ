import { G, TENT, CEDAR, INT, DESK } from './world';

export type V3 = [number, number, number];
export type Env = 'dusk' | 'night' | 'storm' | 'inside' | 'desk' | 'red' | 'dawn' | 'fire';

export interface Shot {
  a: number; b: number; env: Env;
  p0: V3; p1: V3; l0: V3; l1: V3; f0: number; f1: number;
  ease?: 'in' | 'out' | 'io' | 'lin';
  orb?: { c: V3; r0: number; r1: number; h0: number; h1: number; a0: number; a1: number; ly?: number };
  shake?: number; roll?: number; roll1?: number;
  snow?: number; // 0..1 intensity
  fx?: string[]; // e.g. 'flash','whip','red','dolly'
  hud?: string;
}

const P = (x: number, h: number, z: number): V3 => [x, G(x, z) + h, z];
const I = (x: number, y: number, z: number): V3 => [INT.x + x, y, INT.z + z];
const D = (x: number, y: number, z: number): V3 => [DESK.x + x, y, DESK.z + z];

// helper to build a shot
function S(a: number, b: number, env: Env, p0: V3, p1: V3, l0: V3, l1: V3, f0 = 50, f1 = 50, o: Partial<Shot> = {}): Shot {
  return { a, b, env, p0, p1, l0, l1, f0, f1, ease: 'io', ...o };
}
function O(a: number, b: number, env: Env, c: V3, r0: number, r1: number, h0: number, h1: number, a0: number, a1: number, f0 = 50, f1 = 50, o: Partial<Shot> = {}): Shot {
  const dummy: V3 = [0, 0, 0];
  return { a, b, env, p0: dummy, p1: dummy, l0: c, l1: c, f0, f1, ease: 'io', orb: { c, r0, r1, h0, h1, a0, a1 }, ...o };
}

